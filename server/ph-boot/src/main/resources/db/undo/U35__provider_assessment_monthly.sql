-- V35 的回滚脚本（人工执行，Flyway 社区版没有 undo 命令）
--
-- ⚠️ 执行前先确认：这一步会**丢掉全部月度考核分、分数明细与单项分覆盖留痕**。
-- 回滚代价说明：
--
--   - **历史考核分没有第二份副本**：`assessment_monthly_score` 是「某月某店多少分、什么等级」的
--     唯一记录。删掉之后，服务者侧与运营侧的考核页面会一起变空，而**服务者已经据此形成的
--     认知（等级、推荐优先级、续约判断）收不回来**——重跑批算需要重新取数，
--     而当时的数据源（订单统计、券与邀请的事实）在期间可能已经变化，算出来的分**不会与原来相同**。
--   - **覆盖留痕一并消失，这是本条回滚里最贵的一处**：ADR-0039 第三节要求「谁、何时、理由、
--     覆盖前后值都留」，它是服务者申诉时的唯一凭据。删表之后，运营**改过哪一项、为什么改**再也查不到
--     （`audit_log` 只记「调了覆盖接口」这类动作，不记业务值的前后对照）。真要重来，只能靠人工回忆。
--   - **明细（`assessment_item_score`）是总分的解释**：只保留分表也说得过去（分还在），
--     但「这个分怎么来的」会消失——而缺项口径（ADR-0050 第四节）恰恰要求明细里注明「未参与」，
--     没有明细就无法回答「为什么这项没算」。
--   - **`provider.level` / `provider.monthly_score` 不会被本脚本回滚**：那两列在 `provider` 表上
--     （V22 加的），本回滚不动别人的模块；结果就是**门店上留着最近一期的等级与分，而考核记录没了**。
--     如果确实要一起清，需另行人工处理（把 `level` 复位成 1、`monthly_score` 复位成 0.00），
--     这一步**不在本脚本里**——避免回滚一个考核契约时顺手改掉别人模块的数据。
--   - 三张表之间是逻辑引用（没有物理外键），但**必须按分表 → 明细 → 留痕的顺序删**：
--     顺序错了不会报错（没有外键），只会留下指向不存在分表的孤儿行。
--
-- 人工回滚的三步（ADR-0011）：
--   1. 执行本文件；
--   2. DELETE FROM flyway_schema_history WHERE version = '35';
--   3. 重启应用，确认迁移状态。

DROP TABLE IF EXISTS `assessment_override_log`;
DROP TABLE IF EXISTS `assessment_item_score`;
DROP TABLE IF EXISTS `assessment_monthly_score`;
