-- V33 的回滚脚本（人工执行，Flyway 社区版没有 undo 命令）
--
-- ⚠️ 执行前先读清楚它删的是什么：**只删「注册基线」那一条授予**
-- （`code = 'community.post'` 且 `source_ref = 'register:baseline'`）。
--
-- 四件事说清楚：
--   1. **注册流程发的授予与本迁移插的授予是同一形状**（同一个 `source_ref`），
--      所以这个 DELETE 会把**两边一起**删掉——包括本轮之后注册的新账号。这是刻意的：
--      回滚这张迁移的语义是「基线权益这件事没发生过」，而按来源区分「谁是新注册的」没有意义
--      （同一个用户只能有一条基线记录，是不是迁移插的区分不出、也不该区分）；
--   2. **运营手动授予的同码权益不会被动**：手动授予的 `source_ref` 为 NULL
--      （或运营自己填的引用），不在本文件的条件里；
--   3. **邀请 / 打卡 / 订阅来源的授予一条都不动**：本文件从不按 `code` 单独删——
--      只按 `code + source + source_ref` 三者的组合删，避免把「靠邀请挣来的发帖权益」误伤；
--   4. 删除后社区发文的门禁对这一批账号**重新关上**（40300）：这正是回滚这张迁移想要的后果，
--      它说明「注册即可发布」这条路径确实只由这一条记录承载，没有第二处偷偷补上。
--
-- 人工回滚的三步（ADR-0011）：
--   1. 执行本文件；
--   2. DELETE FROM flyway_schema_history WHERE version = '33';
--   3. 重启应用，确认迁移状态。

DELETE FROM `rights_grant`
 WHERE `code` = 'community.post'
   AND `source` = 4
   AND `source_ref` = 'register:baseline';
