/**
 * 写接口的幂等键（ADR-0028）：同一个键的请求服务端只执行一次。
 *
 * 键由前端生成、随请求头 `Idempotency-Key` 送出。**契约的口径是「同一逻辑写操作重试时保持不变」**
 * （contract/common.yaml 对该头的说明），也就是键的有效期是**一次逻辑操作**，不是一次 HTTP 请求。
 *
 * **已知差距（2026-09-30 验收记录在案，尚未修）**：C 端的调用点目前都在「请求真正发出时」
 * 才生成键，于是**用户点了一次、响应丢了、再点一次**会带上不同的键，服务端会当成两次操作
 * ——下单与积分兑换这两处因此可能重复写。请求层的自动重试（网络错误重试一次）不受影响：
 * 它复用同一个请求对象，键不变。修法见验收报告里 F014 的附注（键应在打开表单时生成、
 * 成功后才重置）。
 */

/**
 * 造一个幂等键。
 *
 * 用 UUID 而不是自增/时间戳：键要跨页面、跨重试保持「同一逻辑操作」，也要能安全地并发生成。
 * 环境没有 `randomUUID` 时退化成随机串——**只有唯一性要求，没有密码学要求**（后端只拿它做去重）。
 */
export function newIdempotencyKey(): string {
  const uuid = globalThis.crypto?.randomUUID?.();
  if (uuid) return uuid;
  return `ph-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 12)}`;
}
