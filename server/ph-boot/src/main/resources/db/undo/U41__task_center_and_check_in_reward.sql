-- V41 的回滚脚本（人工执行，Flyway 社区版没有 undo 命令）
--
-- 回滚要撤的与**撤不回**的，分开说：
--   · 撤得掉：打卡得券的档位（表 + 那条 7 天的种子）与「分享」两处的启停；
--   · **撤不掉**：已经发出去的券。`coupon` 里那些行是既成事实，回滚不会也不能撤销它们
--     （用户手里那几张照常在门店核销——发放与核销是两回事）；
--   · 回滚后的效果：打卡不再发券（档位没了），C 端任务列表重新出现「分享给好友」
--     （行为与任务都回到启用），而它的进度仍然恒为 0/1——**这正是本轮要撤掉的那个状态**，
--     所以回滚只有在「AI 建议之外的两件事要退回上一版」时才该做。
--
-- 顺序：先拆档位表（它引用券模板），再恢复启停——启停只动状态位，没有依赖顺序的要求。

DROP TABLE `check_in_reward_rule`;

