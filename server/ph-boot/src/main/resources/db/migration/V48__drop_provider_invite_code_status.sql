-- 删掉门店推广码上的死开关：`provider_invite_code.status`（D-08）
--
-- 背景：V44 建这张表时给了一列 `status`（1 启用 / 0 停用），但**没有任何写入点**——
-- `setStatus` 只在取码时写 1，归因那条路径也从不读它（`InviteService.attributeToProvider`
-- 按码查表就直接建关系）。于是它既不能停用、也不会因为「停用」而失效：
-- 一个谁也改不了、改了什么也不发生的开关，比没有这个字段更糟——它会让运营以为有这回事。
--
-- 为什么是删而不是接线：V44 的设计本意就是「码一旦发出，就代表这家店的拉新入口是开着的」
-- （那一版注释写得清楚）。要做「可停用」得先回答一串业务问题（停用后已发出去的码怎么办、
-- 观察窗内的归因算不算、门店能否自助停用）——那是产品决策，不该由这一列的存在暗示已经定了。
-- 真要停用，另开一片：加回列 + 归因读它 + 服务者侧一个写入端点。
--
-- 回滚见 db/undo/U48（把列加回来，默认 1，与删除前的库内取值一致）。

ALTER TABLE `provider_invite_code`
  DROP COLUMN `status`;
