-- V40 的回滚脚本（人工执行，Flyway 社区版没有 undo 命令）
--
-- ⚠️ 执行前先确认：这一步会**丢掉全部评价**。评价是用户填的唯一一份内容，
-- 无法从别处重建（订单里只有「服务发生过」的事实，没有「用户觉得怎么样」）。
--
-- 回滚代价说明：
--   - **门店评分不会自动回退**：`provider.rating` 是评价聚合出来的**副本**，
--     它由 V40 之后写进去的值仍然留在 `provider` 表里。删掉本表之后那些店会带着
--     「由已不存在的评价算出来的分数」继续参与 C 端排序（`/providers` 按 rating 降序）。
--     所以本脚本最后一步把评分重置回建表前的默认值 5.0——**这是刻意的**：
--     要么回到默认值（可解释：没有评价），要么留下一个无法核对的数字（不可解释）。
--   - **积分流水不会回滚**：评价发出去的 REVIEW 行为分已经入账（`point_record` 的唯一引用
--     是 `review:{orderId}`）。删表之后那几笔分仍在用户账上——它们是既成事实，
--     与 V39 的回滚同理。全部收回需要人工冲正，不是一次 DROP 能表达的。
--   - **回滚不影响订单本身**：`order` 与照片墙、券、号源都不引用本表（逻辑引用，没有外键），
--     已完成的订单仍是已完成，只是「评价过没有」这个事实消失。
--
-- 人工回滚的三步（ADR-0011）：
--   1. 执行本文件；
--   2. DELETE FROM flyway_schema_history WHERE version = '40';
--   3. 重启应用，确认迁移状态。

DROP TABLE IF EXISTS `order_review`;

-- 评分副本一并回到「没有评价」的状态（理由见上）：全部刷回默认值 5.0。
-- 这一步不区分「本来就是默认值的行」与「被评价改过的行」——结果一样，而逐行判反而要多一份
-- 「哪些值是被评价写进去的」的判断，那份判断恰恰随着本表的删除而失去依据。
UPDATE `provider` SET `rating` = 5.0 WHERE `rating` IS NOT NULL;
