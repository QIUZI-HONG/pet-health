-- 但这份**用户能在「AI 免责声明」页读到**的正文仍在承诺——同一个不实话不能只改一半。
--
-- 为什么要新开 V14 而不是改 V8：V8 已经在所有环境执行过（ADR-0011：迁移只前进不回改）。
-- 检索层接上之后可以把这句话改回去，届时同时给出真正的来源。
--
-- 只改正文，不动 `version` / `is_placeholder` / `effective_from`：这不是法务定稿，
-- 只是把一句工程上还不成立的能力描述去掉。

