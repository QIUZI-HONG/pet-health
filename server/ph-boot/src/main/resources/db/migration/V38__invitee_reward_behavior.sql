-- 被邀请人侧的奖励：**只登记行为，默认停用**（F016 的「双方各得」缺的那一半）
--
-- 背景：交付文档 BPM-2 写「好友注册并完善档案 → **双方各得** 20 元洗护券」，而此前只有
-- 邀请人一侧有奖励（有效邀请结算时发积分），被邀请人一侧**既没有行为码也没有发放路径**。
--
-- 本轮裁决（见验收报告第十二节）：
--
--   1. **机制落地、奖励物配置化、默认不发**。这一行 `points = 0`（**0 分 = 记行为不发分**，
--      与种子里 `AI_ADVICE` / `SHARE` 同一编码；这张表的列注释写明了这一点）：
--      运营在积分配置里给它定值之后才会真的发。
--      理由与 ADR-0046 第五节同一条纪律——「奖励物留空是有效状态」：发多少、发什么
--      （券还是分）是产品决策，代码不该替它拍板；而**没有这条行为码，运营连拍的入口都没有**。
--   2. **发放时机与被邀请人「入账」一致性**：与邀请人**同期结算**（24 小时观察窗结束、关系判定有效时），
--      而不是注册即发或建档即发。注册即发会让批量刷号当晚就领到奖励（ADR-0039 的反作弊第三层
--      正是为这个设计的观察窗）；同期发放也让两侧奖励在账上是一件事。
--   3. **一律不占每日上限**（与邀请人侧一致，否则一个 20 分的奖励会当天把上限吃光）；
--      「每有效邀请 1 次」的频次由发分时的 `sourceRef`（`invitee:{关系id}`）保证幂等。
--
-- 为什么复用 `point_behavior` 而不是新建一张「被邀请人奖励配置表」：分值、启停、频次上限
-- 这套配置**已经有运营界面**（积分配置），新表等于把同一类配置拆到两处。
-- 券形态若将来要做，再单开一列/一表（那时才是真的多了一种奖励物）。

