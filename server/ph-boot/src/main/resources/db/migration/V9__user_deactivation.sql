-- 账号注销（切片 #74）
--
-- 交付文档把「数据导出/注销」列为 P0 合规项，conventions.md 又写明「物理删除仅限账号注销场景」。
-- 但**这里仍然不物理删除**，理由是一条比合规口号更硬的约束：留痕。
--
-- 注销做的事（顺序即语义）：
--   1. status 置 2（沿用「禁用」这一位）——登录与刷新令牌立刻拒绝（AccountService 已有这道闸）；
--   2. 手机号与昵称**匿名化**：phone_enc 换成不可还原的标记、phone_hash 换成随机值，
--      于是 `uk_phone_hash` 被让出来，**同一个手机号可以重新注册**（这是注销该有的效果）；
--   3. 宠物与档案软删（is_deleted=1），保留在库里。
--
-- 为什么不物理删除：#121 的审计要求、以及订单/留痕（将来有钱相关的账）不能凭空消失。
-- 若监管口径要求彻底删除，那是另一个动作（数据清理任务），不该藏在注销接口里。

ALTER TABLE `user`
  ADD COLUMN `deactivated_at` DATETIME DEFAULT NULL COMMENT '注销时间；NULL=未注销'
      AFTER `status`;
